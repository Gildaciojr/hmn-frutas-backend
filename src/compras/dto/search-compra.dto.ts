import { IsDateString, IsEnum, IsOptional, IsString } from 'class-validator';

import { StatusCompra } from '@prisma/client';

export class SearchCompraDto {
  //////////////////////////////////////////////////
  // FORNECEDOR
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  fornecedor?: string;

  //////////////////////////////////////////////////
  // FAZENDA
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  fazenda?: string;

  //////////////////////////////////////////////////
  // PLACA
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  placa?: string;

  //////////////////////////////////////////////////
  // ROMANEIO / FOLHA
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  numeroFolha?: string;

  //////////////////////////////////////////////////
  // STATUS
  //////////////////////////////////////////////////

  @IsOptional()
  @IsEnum(StatusCompra)
  status?: StatusCompra;

  //////////////////////////////////////////////////
  // PERÍODO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsDateString()
  dataInicio?: string;

  @IsOptional()
  @IsDateString()
  dataFim?: string;
}
