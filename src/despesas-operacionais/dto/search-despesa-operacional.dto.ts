import {
  IsDateString,
  IsNumberString,
  IsOptional,
  IsString,
} from 'class-validator';

export class SearchDespesaOperacionalDto {
  //////////////////////////////////////////////////
  // ATIVIDADE
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  atividade?: string;

  //////////////////////////////////////////////////
  // DATA INICIAL
  //////////////////////////////////////////////////

  @IsOptional()
  @IsDateString()
  dataInicial?: string;

  //////////////////////////////////////////////////
  // DATA FINAL
  //////////////////////////////////////////////////

  @IsOptional()
  @IsDateString()
  dataFinal?: string;

  //////////////////////////////////////////////////
  // VALOR MÍNIMO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsNumberString()
  valorMinimo?: string;

  //////////////////////////////////////////////////
  // VALOR MÁXIMO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsNumberString()
  valorMaximo?: string;
}
