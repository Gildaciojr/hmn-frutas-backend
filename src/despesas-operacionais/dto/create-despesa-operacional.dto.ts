import {
  IsDateString,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  MaxLength,
  Min,
} from 'class-validator';

export class CreateDespesaOperacionalDto {
  //////////////////////////////////////////////////
  // DATA
  //////////////////////////////////////////////////

  @IsDateString()
  data!: string;

  //////////////////////////////////////////////////
  // ATIVIDADE
  //////////////////////////////////////////////////

  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  atividade!: string;

  //////////////////////////////////////////////////
  // VALOR
  //////////////////////////////////////////////////

  @IsNumber()
  @Min(0.01)
  valor!: number;

  //////////////////////////////////////////////////
  // OBSERVAÇÕES
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(3000)
  observacoes?: string;
}
