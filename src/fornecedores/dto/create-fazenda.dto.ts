import { IsOptional, IsString, MaxLength, MinLength } from 'class-validator';

export class CreateFazendaDto {
  //////////////////////////////////////////////////
  // NOME
  //////////////////////////////////////////////////

  @IsString()
  @MinLength(2)
  @MaxLength(150)
  nome!: string;

  //////////////////////////////////////////////////
  // CIDADE
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(120)
  cidade?: string;

  //////////////////////////////////////////////////
  // ESTADO (UF)
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(2)
  estado?: string;

  //////////////////////////////////////////////////
  // OBSERVAÇÕES
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(3000)
  observacoes?: string;
}
