import {
  IsDateString,
  IsEnum,
  IsNumber,
  IsOptional,
  IsString,
  MaxLength,
  Min,
} from 'class-validator';

import { FormaPagamento } from '@prisma/client';

export class RegistrarPagamentoDto {
  //////////////////////////////////////////////////
  // VALOR
  //////////////////////////////////////////////////

  @IsNumber()
  @Min(0.01)
  valor!: number;

  //////////////////////////////////////////////////
  // FORMA PAGAMENTO
  //////////////////////////////////////////////////

  @IsEnum(FormaPagamento)
  formaPagamento!: FormaPagamento;

  //////////////////////////////////////////////////
  // DATA PAGAMENTO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsDateString()
  pagoEm?: string;

  //////////////////////////////////////////////////
  // VENCIMENTO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsDateString()
  vencimento?: string;

  //////////////////////////////////////////////////
  // OBSERVAÇÕES
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(2000)
  observacoes?: string;
}
