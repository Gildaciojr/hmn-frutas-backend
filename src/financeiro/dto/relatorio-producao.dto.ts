import { IsDateString, IsIn, IsOptional, IsUUID } from 'class-validator';

export class RelatorioProducaoDto {
  ////////////////////////////////////////////////////////////
  // PERÍODO
  ////////////////////////////////////////////////////////////

  @IsDateString()
  dataInicial!: string;

  @IsDateString()
  dataFinal!: string;

  ////////////////////////////////////////////////////////////
  // USUÁRIO
  ////////////////////////////////////////////////////////////

  @IsOptional()
  @IsUUID()
  usuarioId?: string;

  ////////////////////////////////////////////////////////////
  // TIPO
  ////////////////////////////////////////////////////////////

  @IsOptional()
  @IsIn(['COMPRAS', 'VENDAS', 'AMBOS'])
  tipo?: 'COMPRAS' | 'VENDAS' | 'AMBOS';
}
