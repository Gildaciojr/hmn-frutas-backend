import {
  IsEnum,
  IsNumber,
  IsOptional,
  IsString,
  MaxLength,
  Min,
} from 'class-validator';

import { FormaPagamento, TipoTransacao } from '@prisma/client';

export class CreateTransacaoDto {
  //////////////////////////////////////////////////
  // TIPO
  //////////////////////////////////////////////////

  @IsEnum(TipoTransacao)
  tipo!: TipoTransacao;

  //////////////////////////////////////////////////
  // VALOR
  //////////////////////////////////////////////////

  @IsNumber()
  @Min(0.01)
  valor!: number;

  //////////////////////////////////////////////////
  // DESCRIÇÃO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(500)
  descricao?: string;

  //////////////////////////////////////////////////
  // CLIENTE
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  clienteId?: string;

  //////////////////////////////////////////////////
  // REFERÊNCIA
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(120)
  referencia?: string;

  //////////////////////////////////////////////////
  // PAGAMENTO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsEnum(FormaPagamento)
  formaPagamento?: FormaPagamento;

  //////////////////////////////////////////////////
  // DATAS
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  vencimento?: string;

  @IsOptional()
  @IsString()
  pagoEm?: string;

  //////////////////////////////////////////////////
  // OBSERVAÇÕES
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(2000)
  observacoes?: string;
}
