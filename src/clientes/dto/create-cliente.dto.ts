import {
  IsEmail,
  IsEnum,
  IsNumber,
  IsOptional,
  IsString,
  Matches,
  Max,
  MaxLength,
  Min,
  MinLength,
} from 'class-validator';

import { TipoCliente } from '@prisma/client';

export class CreateClienteDto {
  //////////////////////////////////////////////////
  // TIPO CLIENTE
  //////////////////////////////////////////////////

  @IsEnum(TipoCliente)
  tipoCliente!: TipoCliente;

  //////////////////////////////////////////////////
  // NOME
  //////////////////////////////////////////////////

  @IsString()
  @MinLength(3)
  @MaxLength(150)
  nome!: string;

  //////////////////////////////////////////////////
  // TELEFONE
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(25)
  @Matches(/^[0-9()+\-\s]+$/, {
    message: 'Telefone inválido',
  })
  telefone?: string;

  //////////////////////////////////////////////////
  // EMAIL
  //////////////////////////////////////////////////

  @IsOptional()
  @IsEmail()
  @MaxLength(150)
  email?: string;

  //////////////////////////////////////////////////
  // CPF
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(20)
  cpf?: string;

  //////////////////////////////////////////////////
  // CNPJ
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(25)
  cnpj?: string;

  //////////////////////////////////////////////////
  // RAZÃO SOCIAL
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(200)
  razaoSocial?: string;

  //////////////////////////////////////////////////
  // INSCRIÇÃO ESTADUAL
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(50)
  inscricaoEstadual?: string;

  //////////////////////////////////////////////////
  // NOME FANTASIA
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(200)
  nomeFantasia?: string;

  //////////////////////////////////////////////////
  // PROPRIETÁRIO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(150)
  proprietarioNome?: string;

  //////////////////////////////////////////////////
  // ENDEREÇO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(255)
  endereco?: string;

  //////////////////////////////////////////////////
  // BAIRRO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(120)
  bairro?: string;

  //////////////////////////////////////////////////
  // CEP
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(20)
  cep?: string;

  //////////////////////////////////////////////////
  // CIDADE
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(100)
  cidade?: string;

  //////////////////////////////////////////////////
  // ESTADO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(2)
  estado?: string;

  //////////////////////////////////////////////////
  // OBSERVAÇÕES
  //////////////////////////////////////////////////

  @IsOptional()
  @IsString()
  @MaxLength(2000)
  observacoes?: string;

  //////////////////////////////////////////////////
  // DESCONTO PADRÃO
  //////////////////////////////////////////////////

  @IsOptional()
  @IsNumber()
  @Min(0)
  @Max(100)
  descontoPercentual?: number;
}
